import Foundation

/// 아래 탭 바에 서는 두 자리 — 언제(달력) · 무엇부터(할 일).
///
/// **오늘 탭은 없앴다 (1.4.4).** 1.4.3에서 되살렸던 자리인데, 할 일 탭이 생기고
/// 나니 할 일이 겹쳤다 — 오늘 탭이 보여주던 하루 페이지는 달력에서 오늘 칸을
/// 누르면 그대로 나오고, "지금 뭐부터 하지"에는 할 일 탭이 더 잘 답한다. 탭 바에
/// 비슷한 목록이 둘 서 있으면 어느 쪽을 눌러야 하는지 매번 생각해야 한다.
///
/// **달력이 첫 탭인 것은 그대로다.** 1.4.0에서 달력을 홈으로 올린 이유 — 앱은 늘
/// 달력으로 열리는데 달력 화면에 입력창이 없어서 처음 온 사람이 할 일 하나
/// 적어보기까지 길을 찾아야 했다는 것 — 은 지금도 유효하다. 홈 입력창도 그
/// 자리에 그대로 있다.
nonisolated enum AppTab: String, CaseIterable, Sendable {
    /// 달력 홈. 앱을 열면 여기다.
    case calendar
    /// 날짜를 가로지르는 할 일 목록.
    ///
    /// **달력·오늘과 다른 질문에 답한다.** 앞의 둘은 날짜 위에 선 화면이라
    /// 날짜를 아직 안 정한 일이 설 자리가 없었다 — 오늘 페이지 맨 아래 칸에
    /// 들어 있었는데, 적어둔 것이 오늘을 열어야만, 그것도 오늘 할 일들 아래에서야
    /// 보였다. 할 일 앱으로 쓰려는 사람에게는 그게 본진이다.
    case todos

    /// 앱을 열면 보이는 탭. **달력이다** — 열자마자 일정을 확인하는 게 이 앱을
    /// 여는 이유라서, 1.4.0에서 달력을 홈으로 올린 판단을 그대로 둔다.
    static let initial = AppTab.calendar

    /// 이 탭이 로그에 남는 이름. 탭 바를 누른 것을 세는 자리는 `RootTabView`
    /// 하나뿐이다 — 화면들이 각자 자기를 세면 처음 뜰 때 두 번 센다.
    var screen: AnalyticsScreen {
        switch self {
        case .calendar: .calendar
        case .todos: .todos
        }
    }
}
